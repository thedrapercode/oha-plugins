        <!-- Volunteer Policies -->
        <section style="margin-bottom: 40px;">
            <h3 style="color: #2271b1; border-bottom: 2px solid #2271b1; padding-bottom: 10px;">GENERAL POLICIES</h3>
            
            <h4 style="color: #000 !important; background: #fff !important; padding: 5px 0;">Confidentiality</h4>
            <p>All information concerning attendees, staff, financial data, business records, and other volunteers or core staff is confidential. No information may be released without appropriate authorization. This is a basic rule of business ethics.</p>

            <h4 style="color: #000 !important; background: #fff !important; padding: 5px 0;">Identification</h4>
            <p>Volunteers should carry/wear any identifying badges and/or t-shirts given to them by volunteer staff when working their volunteer shift. All volunteers should be easily recognizable by OHC staff and attendees. Any exceptions must be discussed with the volunteer coordinator.</p>

            <h4 style="color: #000 !important; background: #fff !important; padding: 5px 0;">Smoking, Eating, Alcohol and Drug Guidelines</h4>
            <ul>
                <li><strong>Smoking and eating:</strong> Not allowed in any of the main areas of the OSR</li>
                <li><strong>Eating and drinking:</strong> Allowed in the mini bullpen area. Water is allowed in the cell blocks</li>
                <li><strong>Smoking/Vaping:</strong> You may smoke or vape outside of the reformatory and 20 feet from all entry doors</li>
                <li><strong>Alcohol and drugs:</strong> Absolutely prohibited at the OSR. If you are volunteering at any point during the costume ball or after the ball, alcohol is prohibited</li>
            </ul>

            <h4 style="color: #000 !important; background: #fff !important; padding: 5px 0;">Children</h4>
            <p>You may bring a child with you for your shift, if it does not limit your ability to complete your duties. Children must remain under your supervision at all times and are not allowed to roam the OSR during your shift or affect other attendees. They must abide by the same standard that we have for volunteers.</p>

            <h4 style="color: #000 !important; background: #fff !important; padding: 5px 0;">Background Checks</h4>
            <p>A criminal records background check may be required for some volunteer assignments. A volunteer must pass this check to be given an assignment involving money handling, childcare or dealing with sensitive information.</p>
        </section>

