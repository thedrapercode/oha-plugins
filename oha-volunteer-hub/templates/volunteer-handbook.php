                <p style="margin-bottom: 0; color: #721c24 !important;">All human blood and body fluids are to be treated as if they were infectious for HIV, Hepatitis B and other blood-borne pathogens. Volunteers should immediately inform the volunteer coordinator and support person if they believe they have been exposed to infection.</p>
